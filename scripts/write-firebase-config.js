// Write public/firebase-config.js from the FIREBASE_WEB_API_KEY environment variable.
// The key is kept out of git (GitHub secret in CI, env var locally). It's a public web
// key by design — browsers receive it — so the real protection is the key's website
// restriction plus the Firestore rules; this just keeps it out of the repository.
// Usage: FIREBASE_WEB_API_KEY=... node scripts/write-firebase-config.js
import { writeFile } from "node:fs/promises";

// Strip whitespace and any byte-order mark (Windows shells can add one when setting the secret).
const apiKey = (process.env.FIREBASE_WEB_API_KEY ?? "").replace(/^﻿/, "").trim();
if (!/^AIza[\w-]{35}$/.test(apiKey)) {
  console.error("FIREBASE_WEB_API_KEY is missing or not a Google API key.");
  process.exit(1);
}
const config = {
  apiKey,
  authDomain: "pistachio-kitchen.firebaseapp.com",
  projectId: "pistachio-kitchen",
  storageBucket: "pistachio-kitchen.firebasestorage.app",
  messagingSenderId: "720061481410",
  appId: "1:720061481410:web:f188eea83a51b4587dd65b",
};
await writeFile(new URL("../public/firebase-config.js", import.meta.url),
  `// Generated by scripts/write-firebase-config.js — not committed.\nexport const FIREBASE_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log("wrote public/firebase-config.js");
