// Regenerate public/lib/hero-meta.js from OpenDota's hero list (run when a hero is added).
// Usage: node scripts/gen-hero-meta.js
import { writeFile } from "node:fs/promises";

const heroes = await (await fetch("https://api.opendota.com/api/heroes")).json();
const display = (n) => (n === "Ring Master" ? "Ringmaster" : n); // match the in-game scoreboard
const rows = heroes.sort((a, b) => a.id - b.id).map((h) => [h.id, display(h.localized_name), h.name.replace("npc_dota_hero_", "")]);

const src = `// Generated by scripts/gen-hero-meta.js from OpenDota /api/heroes: [id, display name, image slug].
export const HERO_META = ${JSON.stringify(rows)};

const CDN = "https://cdn.cloudflare.steamstatic.com/apps/dota2/images/dota_react/heroes/";
const byName = new Map(HERO_META.map(([, n, s]) => [n.toLowerCase(), s]));
const byId = new Map(HERO_META.map(([id, n, s]) => [id, { id, name: n, slug: s }]));

export const heroById = (id) => byId.get(id) ?? null;
export function heroImg(name) {
  const slug = byName.get(String(name ?? "").toLowerCase());
  return slug ? CDN + slug + ".png" : null;
}
`;
await writeFile(new URL("../public/lib/hero-meta.js", import.meta.url), src);
console.log(`wrote public/lib/hero-meta.js (${rows.length} heroes)`);
